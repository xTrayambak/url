func percentEncode*(
    input: StringView, characterSet: openArray[uint8]
): string {.cdecl.} =
  var flag = -1

  for i, c in input:
    if characterSet.bitAt(cast[uint8](c)):
      break

    flag = i

  let numChars = int(input.len) - 1
  if flag == -1 or flag == numChars:
    # Optimization: Don't iterate if no character requires
    # percent encoding.
    return $input

  var res = newStringOfCap(numChars)
    # In the worst case, percent encoding might produce 3 characters.

  # res &= input[0 ..< (input.len - flag)]

  for c in input:
    if characterSet.bitAt(cast[uint8](c)):
      res &= '%'
      res &= toHex(cast[uint8](c))
    else:
      res &= c

  ensureMove(res)

func percentDecode*(input: StringView, firstPercent: uint32): string =
  if firstPercent == cast[uint32](-1):
    return $input

  var dest = newStringOfCap(input.len)
  dest &= $input.slice(0'u32, firstPercent)

  var pntr = firstPercent
  let stop = input.len

  while pntr < stop:
    let ch = input[pntr]
    let remaining = stop - pntr - 1'u32

    if ch != '%' or remaining < 2 or
        (not isAsciiHexDigit(input[pntr + 1]) or not isAsciiHexDigit(input[pntr + 2])):
      dest &= ch
      inc pntr
    else:
      let
        a = convertHexToBinary(input[pntr + 1])
        b = convertHexToBinary(input[pntr + 2])

        c = cast[char](a * 16'u8 + b)

      dest &= c
      pntr += 3

  ensureMove(dest)

